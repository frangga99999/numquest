// Ambil terjemahan; kembalikan kunci mentah kalau tidak ditemukan.
export function t(key, lang = 'id') {
  const entry = DICT[key]
  if (!entry) return key
  return entry[lang] || entry.id || key
}

// Ganti placeholder {name} dalam string hasil terjemahan.
export function tf(key, lang, vars = {}) {
  let s = t(key, lang)
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}
